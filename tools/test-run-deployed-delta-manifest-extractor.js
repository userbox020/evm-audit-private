function sentinel(status = "unchanged", selectedPaths = ["config/137/My Manifest.json"], repositoryId = sentinelModule.REPOSITORIES[0].id) {
  const generatedAt = new Date(NOW - 60_000).toISOString();
  const repositories = sentinelModule.REPOSITORIES.map((repository, index) => {
    const candidate = status === "candidate-change" && repository.id === repositoryId;
    return {
      id: repository.id,
      officialUrl: repository.officialUrl,
      defaultBranch: "main",
      sourceClass: repository.sourceClass,
      observedHeadSha: sha40(index + 101),
      previousHeadSha: sha40(index + 1),
      releaseIds: [], tags: [],
      configuredManifestPaths: [...sentinelModule.MANIFEST_PREFIXES],
      changedManifestPaths: candidate ? [...selectedPaths] : [],
      changeHints: candidate ? ["unknown"] : [],
      chainTextHints: [], evidenceUrls: [], etagByUrl: {},
      pollStatus: candidate ? "candidate-change" : "unchanged",
      observedAt: generatedAt
    };
  });
  return {
    schema: sentinelModule.SCHEMA,
    generatedAt,
    runId: "manifest-extractor-test-run",
    status,
    baselineCreated: false,
    repositories
  };
}

