    await assert.rejects(extractor.runAndPublish({
      sentinelPath: paths.sentinelPath, scorerPath: paths.scorerPath, outputPath: paths.outputPath,
      authorityOutputPath: paths.authorityOutputPath, binderOutputPath: paths.binderOutputPath,
      fsImpl: fs, now: NOW, transport
    }), (error) => error instanceof extractor.ExtractorError);
