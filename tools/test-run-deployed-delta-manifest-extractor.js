function writeInputs(paths, input, scorer = scorerModule.scoreSentinel(input, NOW)) {
  fs.writeFileSync(paths.sentinelPath, `${JSON.stringify(input, null, 2)}\n`);
  if (scorer !== null) fs.writeFileSync(paths.scorerPath, `${JSON.stringify(scorer, null, 2)}\n`);
  return scorer;
}

function contentsResponse(filePath, bytes, overrides = {}) {
  const value = {
    type: "file",
    path: filePath,
    sha: extractor.gitBlobSha(bytes),
    size: bytes.length,
    encoding: "base64",
    content: bytes.toString("base64"),
    ...overrides
  };
  return {
    status: 200,
    headers: { "content-type": "application/vnd.github+json; charset=utf-8" },
    body: JSON.stringify(value)
  };
}

