async function run(paths, input, transport, scorer, extra = {}) {
  writeInputs(paths, input, scorer === undefined ? scorerModule.scoreSentinel(input, NOW) : scorer);
  return extractor.runAndPublish({
    sentinelPath: paths.sentinelPath,
    scorerPath: paths.scorerPath,
    outputPath: paths.outputPath,
    mappingOutputPath: paths.mappingOutputPath,
    metadataOutputPath: paths.metadataOutputPath,
    authorityOutputPath: paths.authorityOutputPath,
    binderOutputPath: paths.binderOutputPath,
    invariantOutputPath: paths.invariantOutputPath,
    fsImpl: fs,
    now: NOW,
    transport,
    ...extra
  });
}

