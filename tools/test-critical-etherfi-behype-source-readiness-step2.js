#!/usr/bin/env node
"use strict";

const assert = require("assert");
const crypto = require("crypto");
const fs = require("fs");
const path = require("path");
const ROOT = path.resolve(__dirname, "..");
const NAME = "critical-etherfi-behype-source-readiness-step2";
const RAW = `reports/raw/fast/${NAME}.json`;
const MANIFEST = `reports/raw/fast/${NAME}-manifest.json`;
const REPORT = `reports/${NAME}.md`;
const INBOX = `coordination/inbox/critical/2026-07-23-${NAME}.json`;
const HANDOFF = `coordination/handoffs/2026-07-23-${NAME}-handoff.md`;
const REVISION = "behype-source-readiness-step2-offline-exhaustive-r1";
const abs = (x) => path.join(ROOT, x);
const hash = (x) => crypto.createHash("sha256").update(x).digest("hex");

const rawText = fs.readFileSync(abs(RAW), "utf8");
const raw = JSON.parse(rawText);
const manifestText = fs.readFileSync(abs(MANIFEST), "utf8");
const manifest = JSON.parse(manifestText);
const report = fs.readFileSync(abs(REPORT), "utf8");
const inboxText = fs.readFileSync(abs(INBOX), "utf8");
const inbox = JSON.parse(inboxText);
const handoff = fs.readFileSync(abs(HANDOFF), "utf8");

assert.strictEqual(raw.revision, REVISION);
assert.strictEqual(raw.classification, "INCOMPLETE/WATCH/SOURCE-READINESS-BLOCKED/RETAINED-STEP4-BINDINGS-NOT-LOCALLY-REPRODUCIBLE");
assert.deepStrictEqual(raw.pipeline, { stage: 0, totalStages: 5, upgraded: false });
assert.strictEqual(raw.routePositive, 0);
assert.strictEqual(raw.executableNow, 0);
assert.strictEqual(raw.signedActionJustified, false);
assert.strictEqual(raw.fork, false);
assert.strictEqual(raw.safety.localWorkspaceOnly, true);
for (const k of ["rpcUsed", "endpointInventoryRead", "graphqlInventoryRead", "webUsed", "forkCreated", "liveCalls", "stateMutation", "signingUsed", "envOrSecretFilesRead"]) assert.strictEqual(raw.safety[k], false, k);
assert.strictEqual(raw.searchMethod.deterministicSortedTraversal, true);
assert.strictEqual(raw.searchMethod.largeFilesStreamScanned, true);
assert.strictEqual(raw.searchMethod.filesystemSourceAndBuildSearchAllWorkspace, true);
assert(raw.searchMethod.gitRepositoriesDiscovered >= raw.searchMethod.gitObjectPathsProtocolRelatedRepos.length);
assert(raw.searchMethod.gitObjectPathsProtocolRelatedRepos.some((x) => /cash-v3$/i.test(x)));
assert.strictEqual(raw.searchMethod.symlinksNotFollowed, true);
assert(raw.search.counters.directoriesVisited > 100);
assert(raw.search.counters.filesVisited > 1000);
assert(raw.search.counters.textFilesScanned > 1000);
assert(raw.search.counters.bytesContentScanned > 1_000_000);
assert(raw.search.gitRepos.length > 0);
assert(raw.search.gitRepos.every((x) => typeof x.revListOk === "boolean"));
assert(raw.search.gitObjectAndHistoryHits.some((x) => x.interfaceOnly === true && /IL2BeHYPEOAppStaker\.sol$/.test(x.path)));
assert(raw.search.hits.some((x) => x.path === "targets/cash-v3/src/interfaces/IL2BeHYPEOAppStaker.sol" && x.category === "interface-source"));
assert(raw.search.hits.some((x) => x.path === "reports/raw/fast/critical-etherfi-behype-staker-layerzero-binding.json"));
assert.strictEqual(raw.summaryCounts.componentCount, 9);
assert.strictEqual(raw.summaryCounts.reproducibleComponentsNow, 0);
assert.strictEqual(raw.summaryCounts.predecessorLocalExactRuntimeComponents, 4);
assert(raw.summaryCounts.predecessorExplorerRuntimeExactComponents >= 8);
assert.strictEqual(raw.summaryCounts.customSourceBodyHits, 0);
assert.strictEqual(raw.summaryCounts.exactStandardJsonHits, 0);
assert.strictEqual(raw.summaryCounts.exactBuildInfoHits, 0);
assert(raw.summaryCounts.standardJsonContextHits >= 1);
assert(raw.summaryCounts.buildInfoContextHits >= 1);
assert.strictEqual(raw.summaryCounts.bytecodePayloadHits, 0);
assert.strictEqual(raw.summaryCounts.gitCustomBodyHits, 0);
assert(raw.summaryCounts.compilerCacheObjects >= raw.summaryCounts.exactCompilerCandidates);
assert.strictEqual(raw.componentMatrix.length, 9);
for (const row of raw.componentMatrix) {
  assert.strictEqual(row.exactCustomSourceBodyPresent, false, row.id);
  assert.strictEqual(row.exactStandardJsonPresent, false, row.id);
  assert.strictEqual(row.exactBuildInfoPresent, false, row.id);
  assert.strictEqual(row.creationBytecodePresent, false, row.id);
  assert.strictEqual(row.deployedRuntimeBytesPresent, false, row.id);
  assert.strictEqual(row.cborOrIpfsMetadataSnapshotPresent, false, row.id);
  assert.strictEqual(row.exactCompilerBinaryPresentInWorkspace, row.exactCompilerCandidates.length > 0, row.id);
  assert.strictEqual(row.deterministicLocalCompilationAttempted, false, row.id);
  assert.strictEqual(row.reproducibleBuildPossibleNow, false, row.id);
  assert.strictEqual(row.currentRunIndependentRuntimeEquivalence, false, row.id);
  assert(row.missingObjects.length >= 6, row.id);
}
assert.strictEqual(raw.componentMatrix.filter((x) => x.predecessorLocalExactBuildRuntime).length, 4);
assert(raw.componentMatrix.some((x) => x.id === "destination-behype-adapter-proxy" && x.missingObjects.some((m) => m.includes("implementation identity"))));
for (const [k, v] of Object.entries(raw.exactSourceReadiness)) if (k !== "exactCompilerBinaryFound") assert.strictEqual(v, false, k);
assert.strictEqual(raw.exactSourceReadiness.exactCompilerBinaryFound, raw.summaryCounts.exactCompilerCandidates > 0);
assert.strictEqual(raw.compileAttempts.length, 9);
assert(raw.compileAttempts.every((x) => x.attempted === false && x.reason.includes("exact standard-json")));
assert.strictEqual(raw.findings.modelCandidateUpgraded, false);
assert.strictEqual(raw.findings.pipelineUpgraded, false);
assert.strictEqual(raw.findings.productionPrimitiveEstablished, false);
assert.strictEqual(raw.findings.permissionlessLossEstablished, false);
assert.strictEqual(raw.findings.attackerProfitEstablished, false);
assert(raw.blockers.length >= 6);

assert.strictEqual(manifest.revision, REVISION);
assert.strictEqual(manifest.runId, raw.runId);
assert.strictEqual(manifest.classification, raw.classification);
assert.strictEqual(manifest.pipeline, "0/5");
assert.strictEqual(manifest.offlineOnly, true);
assert.strictEqual(manifest.exhaustiveWorkspaceTraversal, true);
assert.strictEqual(manifest.localGitObjectSearch, true);
assert.strictEqual(manifest.secretFilesRead, false);
assert.strictEqual(manifest.exactCustomSourceFound, false);
assert.strictEqual(manifest.exactStandardJsonFound, false);
assert.strictEqual(manifest.targetRuntimeOrCreationBytesFound, false);
assert.strictEqual(manifest.deterministicCompilationAttempted, false);
assert.strictEqual(manifest.currentRunRuntimeEquivalenceEstablished, false);
assert.strictEqual(manifest.modelCandidateUpgraded, false);
assert.strictEqual(manifest.componentCount, 9);
assert.strictEqual(inbox.runId, raw.runId);
assert.strictEqual(inbox.pipeline, "0/5");
for (const rec of manifest.records) {
  const data = fs.readFileSync(abs(rec.path));
  assert.strictEqual(data.length, rec.bytes, `bytes ${rec.path}`);
  assert.strictEqual(hash(data), rec.sha256, `hash ${rec.path}`);
}
assert.strictEqual(hash(manifest.records.map((x) => `${x.path}\0${x.bytes}\0${x.sha256}`).join("\n")), manifest.aggregateSha256);
const leak = [rawText, manifestText, report, inboxText, handoff].join("\n");
assert(!/https?:\/\/[a-z0-9]/i.test(leak), "URL leak");
assert(!/[?&](?:key|token|api_key|apikey)=/i.test(leak), "credential leak");
assert(!/(authorization|cookie|set-cookie)\s*[:=]/i.test(leak), "header leak");
assert(report.includes("🟠 WATCH"));
assert(report.includes("Pipeline:** `0/5`"));
assert(report.includes("No guessed proxy/dependency rebuild was attempted"));
assert(report.includes("nextGate"));
assert(handoff.includes(raw.runId));
process.stdout.write(`PASS EtherFi BeHYPE source readiness Step 2 (${raw.runId}; components=${raw.componentMatrix.length}; files=${raw.search.counters.filesVisited}; repos=${raw.search.gitRepos.length}; records=${manifest.records.length}; ${manifest.aggregateSha256})\n`);
