function registryFor(chainName) {
  const list = FACTORY_REGISTRY[chainName];
  return Array.isArray(list) ? list : [];
}

function registryStats() {
  const out = {};
  for (const [chain, list] of Object.entries(FACTORY_REGISTRY)) out[chain] = list.length;
  return out;
}

