/*
 * tools/lib/factory-creation-registry.js
 *
 * Explicit, bounded, reviewable registry of factory / registry / market-creator
 * contracts per chain whose creation events emit the address of a NEWLY DEPLOYED
 * contract. Used by tools/scan-new-deployments-by-block.js to close the factory /
 * CREATE2 inner-deployment blind spot of a `to === null` block scan.
 *
 * Rules for this file:
 *   - Data only. No endpoint values, credentials, headers, or I/O.
 *   - Every entry is a real deployed contract address plus the exact event ABI
 *     fragment it emits when it creates a child contract, including the deployed
 *     `indexed` layout. The layout matters: eth_getLogs filters on topic0 (which
 *     is indexed-independent), but decoding the created address with ethers
 *     parseLog requires indexed markers to match the on-chain log shape.
 *   - The `event` fragments below were confirmed against explorer-verified ABIs
 *     with `--probe-registry` (see matchedEvent output).
 *   - `createdIndex` is the positional argument holding the created address.
 *     `createdArg` is the named argument (kept for readability).
 *   - `filter` (optional) restricts which emitted events count as creations.
 *   - `expectName` is the explorer-verified contract name used by `--probe-registry`
 *     to confirm the address has not been repointed to unrelated code.
 *
 * This registry is intentionally small and curated rather than exhaustive. New
 * entries must be added with a source note and pass `--probe-registry`.
 */

