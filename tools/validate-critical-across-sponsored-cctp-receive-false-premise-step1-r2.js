"use strict";

const fs = require("fs");
const path = require("path");
const crypto = require("crypto");
const NAME = "critical-across-sponsored-cctp-receive-false-premise-step1-r2";
const CLASSIFICATION = "CLOSED/FALSE-PERMISSIONLESS-PREMISE/SCOPED-EOA-SOURCE-SEMANTICS/PRIVILEGED-EMERGENCY-AND-SWEEPER/CCTP-ATTESTED-FEE-EXECUTED/SIGNED-MAX-FEE/PREEXISTING-BALANCE-PROTECTED";
const ROOT = path.resolve(__dirname, "..");
const RAW = `reports/raw/fast/${NAME}.json`;
const TESTS = `reports/raw/fast/${NAME}-tests.json`;
const MANIFEST = `reports/raw/fast/${NAME}-manifest.json`;
const INBOX = `coordination/inbox/critical/2026-07-26-${NAME}.json`;
const read = (relative) => fs.readFileSync(path.join(ROOT, relative));
const json = (relative) => JSON.parse(read(relative));
const sha = (value) => crypto.createHash("sha256").update(value).digest("hex");
const checks = [];
const check = (condition, label) => { if (!condition) throw new Error(label); checks.push(label); };
const aggregateFor = (records) => sha(Buffer.from(records.map((row) => `${row.path}\0${row.bytes}\0${row.sha256}`).join("\n")));

const raw = json(RAW);
const tests = json(TESTS);
const manifest = json(MANIFEST);
const inbox = json(INBOX);
check(raw.classification === CLASSIFICATION && manifest.classification === CLASSIFICATION, "classification");
check(raw.pipeline.branch === 0 && raw.pipeline.total === 5, "branch-0-of-5");
check(raw.gates.routePositive === 0 && raw.gates.executableNow === 0 && raw.gates.signedActionJustified === false && raw.gates.fork === false, "gates");
check(raw.conclusions.feeSemantics.quoteSignatureBindsMaxFee === true, "signature-binds-max-fee");
check(raw.conclusions.feeSemantics.quoteSignatureBindsFeeExecuted === false, "signature-excludes-fee-executed");
check(raw.conclusions.feeSemantics.freshAttestedFeeExecutedAtOrBelowMaxFeeAccepted === true, "fresh-fees-accepted");
check(raw.conclusions.feeSemantics.feeExecutedAboveMaxFee.includes("CCTP-enforcement mock"), "above-max-mock-rejected");
check(raw.conclusions.feeSemantics.staleAttestationFeeMutationFailureLayer === "CCTP transmitter, not quote signature", "fee-failure-attribution");
check(raw.conclusions.feeSemantics.maxFeeMutationWithFreshAttestation === "InvalidSignature", "max-fee-signature");
check(raw.conclusions.authorization.normalSubmissionPermissionless === true && raw.conclusions.authorization.arbitraryCallerSweep === false, "permissionless-submit-no-sweep");
check(raw.conclusions.authorization.strandedFundSweep === "FUNDS_SWEEPER_ROLE", "privileged-sweep");
check(raw.conclusions.custodyRisk.includes("privileged custody/trust risk"), "custody-risk");
check(raw.conclusions.preservedRegression.length === 5 && raw.conclusions.permissionlessProfit === 0, "preserved-regression-negative-profit");
check(tests.testsPassed === 19 && tests.testsFailed === 0 && tests.predecessorTests === 13 && tests.r2Tests === 6, "test-counts");
check(tests.fuzzCases === 512 && tests.effectiveCases === 529 && tests.fuzzTestFunctions === 2, "fuzz-counts");
check(tests.deterministicReplay === true && tests.replayCount === 2 && /^[0-9a-f]{64}$/.test(tests.normalizedPassOutputSha256), "deterministic-replay");
check(tests.isolatedCompile.deployedRuntimeEquivalence === false && tests.isolatedCompile.erc1271Covered === false, "scope-limits");
check(tests.isolatedCompile.limitations.includes("mint-recipient overrides") && tests.isolatedCompile.limitations.includes("not Circle code"), "mock-limits");
check(raw.predecessor.aggregateSha256 === manifest.predecessor.aggregateSha256 && raw.predecessor.manifestSha256 === manifest.predecessor.manifestSha256, "predecessor-binding");
check(raw.productionBinding.commit === manifest.productionCommit && raw.productionBinding.sources.length === 9 && raw.productionBinding.productionSourcesModified === false, "production-binding");
check(raw.activityScope.rpcCalls === 0 && raw.activityScope.httpRequests === 0 && raw.activityScope.forkCreated === false && raw.activityScope.signing === false && raw.activityScope.broadcasts === 0, "offline-safety");
check(inbox.routePositive === 0 && inbox.executableNow === 0 && inbox.signedActionJustified === false && inbox.fork === false, "inbox-gates");
const records = manifest.records.map((item) => {
  const value = read(item.path);
  check(value.length === item.bytes && sha(value) === item.sha256, `record:${item.path}`);
  return { path: item.path, bytes: value.length, sha256: sha(value) };
});
const aggregate = aggregateFor(records);
check(aggregate === manifest.aggregateSha256, "aggregate");
process.stdout.write(`${JSON.stringify({ ok: true, checksPassed: checks.length, checksTotal: checks.length, runId: raw.runId, classification: CLASSIFICATION, tests: "19/19", fuzzCases: tests.fuzzCases, effectiveCases: tests.effectiveCases, replayCount: tests.replayCount, normalizedPassOutputSha256: tests.normalizedPassOutputSha256, r2HarnessRuntimeSha256: tests.isolatedCompile.r2HarnessRuntimeSha256, predecessorAggregateSha256: raw.predecessor.aggregateSha256, predecessorManifestSha256: raw.predecessor.manifestSha256, manifestSha256: sha(read(MANIFEST)), aggregateSha256: aggregate })}\n`);
