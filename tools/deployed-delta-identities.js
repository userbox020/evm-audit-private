#!/usr/bin/env node
"use strict";

const AAVE_ADDRESS_BOOK_REPOSITORY = "aave-dao/aave-address-book";
const CURVE_CORE_REPOSITORY = "curvefi/curve-core";
const VETRO_REPOSITORY = "vetro-protocol/vetro-contracts";
const BASEDOLLAR_REPOSITORY = "basedollar/basedollar";

const ETHEREUM_CHAIN_ID = "1";
const BASE_CHAIN_ID = "8453";
const AVALANCHE_CHAIN_ID = "43114";
const AAVE_INK_CHAIN_ID = "57073";
// Aave/Curve XLayer deployments are a real chain, but they are outside the watched 1/8453-set;
// mapped factually here and filtered by the watched-chain allowlist downstream.
const XLAYER_CHAIN_ID = "196";

const AAVE_INK_PATHS = Object.freeze([
  "src/AaveV3InkWhitelabel.sol",
  "src/ts/AaveV3InkWhitelabel.ts"
]);

// Paths the extractor's Aave address-book adapter can parse (autogenerated source projections).
const EXACT_PATH_IDENTITIES = Object.freeze(Object.fromEntries(
  AAVE_INK_PATHS.map((filePath) => [`${AAVE_ADDRESS_BOOK_REPOSITORY}\0${filePath}`, AAVE_INK_CHAIN_ID])
));

// Filename-grounded chain resolution for the watched families. Chain ids come only from
// repository + exact verified path identities (never from file content, cycle state, or network
// calls). Used by prefilter evidence resolution; the extractor keeps using the narrower
// `exactChainIdForPath` set because only those paths have an adapter parser.
//
// Aave address-book: only the mainnet files (testnet variants such as *Sepolia are deliberately
// excluded). Curve-core `deployments/prod/` has no `ethereum.yaml`/`base.yaml`; only the
// chain-named files whose chain id is unambiguous are mapped, and the rest (arc, robinhood, ...)
// stay out of scope. Never guess chains.
const AAVE_ETHEREUM_FILES = Object.freeze([
  "src/AaveV3Ethereum.sol", "src/ts/AaveV3Ethereum.ts",
  "src/AaveV3EthereumEtherFi.sol", "src/ts/AaveV3EthereumEtherFi.ts",
  "src/AaveV3EthereumHorizon.sol", "src/ts/AaveV3EthereumHorizon.ts",
  "src/AaveV3EthereumLido.sol", "src/ts/AaveV3EthereumLido.ts",
  "src/AaveV4Ethereum.sol", "src/ts/AaveV4Ethereum.ts",
  "scripts/configs/v4/ethereum.ts"
]);
const AAVE_BASE_FILES = Object.freeze([
  "src/AaveV3Base.sol", "src/ts/AaveV3Base.ts",
  "src/AaveV4Base.sol", "src/ts/AaveV4Base.ts"
]);
const AAVE_XLAYER_FILES = Object.freeze([
  "src/AaveV3XLayer.sol", "src/ts/AaveV3XLayer.ts"
]);
const RESOLVED_PATH_IDENTITIES = Object.freeze([
  ...AAVE_ETHEREUM_FILES.map((filePath) => [AAVE_ADDRESS_BOOK_REPOSITORY, filePath, ETHEREUM_CHAIN_ID]),
  ...AAVE_BASE_FILES.map((filePath) => [AAVE_ADDRESS_BOOK_REPOSITORY, filePath, BASE_CHAIN_ID]),
  ...AAVE_XLAYER_FILES.map((filePath) => [AAVE_ADDRESS_BOOK_REPOSITORY, filePath, XLAYER_CHAIN_ID]),
  ...AAVE_INK_PATHS.map((filePath) => [AAVE_ADDRESS_BOOK_REPOSITORY, filePath, AAVE_INK_CHAIN_ID]),
  [CURVE_CORE_REPOSITORY, "deployments/prod/avalanche.yaml", AVALANCHE_CHAIN_ID],
  [CURVE_CORE_REPOSITORY, "deployments/prod/ink.yaml", AAVE_INK_CHAIN_ID],
  [CURVE_CORE_REPOSITORY, "deployments/prod/x_layer.yaml", XLAYER_CHAIN_ID],
  // VETRO commits per-chain hardhat-deploy artifacts under `deployments/<chain>/`; the
  // deployment chain is fixed by the directory (deployments/ethereum/.chainId === 1).
  [VETRO_REPOSITORY, "deployments/ethereum/.chainId", ETHEREUM_CHAIN_ID],
  // Base Dollar address books: `1.json` is Ethereum mainnet; the Sepolia file is not watched.
  [BASEDOLLAR_REPOSITORY, "contracts/addresses/1.json", ETHEREUM_CHAIN_ID],
]);
const RESOLVED_PATH_MAP = Object.freeze(Object.fromEntries(
  RESOLVED_PATH_IDENTITIES.map(([repositoryId, filePath, chainId]) => [`${repositoryId}\0${filePath}`, chainId])
));
// Directory-prefix chain resolution for repositories that commit a per-chain deployment
// directory. The chain id is fixed by the directory, never inferred from file content.
const RESOLVED_PATH_PREFIXES = Object.freeze([
  [VETRO_REPOSITORY, "deployments/ethereum/", ETHEREUM_CHAIN_ID],
]);

function exactChainIdForPath(repositoryId, filePath) {
  if (typeof repositoryId !== "string" || typeof filePath !== "string") return null;
  return EXACT_PATH_IDENTITIES[`${repositoryId}\0${filePath}`] || null;
}

function exactChainIdsForPaths(repositoryId, filePaths) {
  if (!Array.isArray(filePaths)) return [];
  return [...new Set(filePaths.map((filePath) => exactChainIdForPath(repositoryId, filePath)).filter(Boolean))]
    .sort((left, right) => left.localeCompare(right));
}

function chainIdForPath(repositoryId, filePath) {
  if (typeof repositoryId !== "string" || typeof filePath !== "string") return null;
  const exact = RESOLVED_PATH_MAP[`${repositoryId}\0${filePath}`];
  if (exact) return exact;
  for (const [id, prefix, chainId] of RESOLVED_PATH_PREFIXES) {
    if (repositoryId === id && filePath.startsWith(prefix)) return chainId;
  }
  return null;
}

function chainIdsForPaths(repositoryId, filePaths) {
  if (!Array.isArray(filePaths)) return [];
  return [...new Set(filePaths.map((filePath) => chainIdForPath(repositoryId, filePath)).filter(Boolean))]
    .sort((left, right) => left.localeCompare(right));
}

module.exports = Object.freeze({
  AAVE_ADDRESS_BOOK_REPOSITORY,
  CURVE_CORE_REPOSITORY,
  VETRO_REPOSITORY,
  BASEDOLLAR_REPOSITORY,
  ETHEREUM_CHAIN_ID,
  BASE_CHAIN_ID,
  AVALANCHE_CHAIN_ID,
  AAVE_INK_CHAIN_ID,
  XLAYER_CHAIN_ID,
  AAVE_INK_PATHS,
  AAVE_ETHEREUM_FILES,
  AAVE_BASE_FILES,
  AAVE_XLAYER_FILES,
  RESOLVED_PATH_IDENTITIES,
  RESOLVED_PATH_PREFIXES,
  exactChainIdForPath,
  exactChainIdsForPaths,
  chainIdForPath,
  chainIdsForPaths,
});
