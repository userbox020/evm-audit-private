class ExtractorError extends Error {
  constructor(code) { super(code); this.name = "ExtractorError"; this.code = code; }
}

function fail(code) { throw new ExtractorError(code); }
function ownObject(value) { return value !== null && typeof value === "object" && !Array.isArray(value); }
function exactKeys(value, keys) {
  return ownObject(value) && JSON.stringify(Object.keys(value).sort()) === JSON.stringify([...keys].sort());
}
function iso(value) {
  return typeof value === "string" && Number.isFinite(Date.parse(value)) && new Date(value).toISOString() === value;
}
function sha40(value, nullable = false) {
  return (nullable && value === null) || (typeof value === "string" && /^[0-9a-f]{40}$/.test(value));
}
function sha64(value, nullable = false) {
  return (nullable && value === null) || (typeof value === "string" && /^[0-9a-f]{64}$/.test(value));
}
function safeRepositoryId(value) {
  return typeof value === "string" && value.length > 0 && value.length <= 200
    && /^[A-Za-z0-9_.-]+\/[A-Za-z0-9_.-]+$/.test(value) && !value.includes("..");
}
function eligiblePath(repositoryId, value) {
  // The extractor only claims bounded JSON manifest parsing plus the exact adapter source paths
  // in `exactChainIdForPath` (currently the Aave Ink autogenerated projections). Curve
  // `deployments/prod/*.yaml` and non-Ink Aave `.sol`/`.ts` files are chain-resolved by the
  // prefilter but are intentionally not requested here: there is no bounded YAML parser, the
  // curve adapter requires an already-parsed manifest object, and the Aave adapter is
  // Ink-specific. Fetching them only to fail would abort the whole bounded run.
  return typeof value === "string" && value.length > 0 && value.length <= 1024
    && (identityModule.exactChainIdForPath(repositoryId, value) !== null
      || (ALLOWED_PREFIXES.some((prefix) => value.startsWith(prefix)) && /\.json$/i.test(value)))
    && !value.startsWith("/")
    && !value.includes("\\") && !value.includes("//") && !value.split("/").includes("..")
    && !/[\u0000-\u001f\u007f]/.test(value) && !ADDRESS_TEXT.test(value)
    && !DOMAIN_TEXT.test(value) && !LEAK_TEXT.test(value);
}
function numericChainId(value) { return typeof value === "string" && /^[1-9][0-9]{0,19}$/.test(value); }
function safetyFields(networkAccess) {
  return {
    localOnly: !networkAccess, networkAccess, rpcAccess: false, forkUse: false, pnlEvaluation: false,
    signing: false, transactions: false, automaticExecution: false
  };
}
function leakFree(value) {
  const serialized = JSON.stringify(value);
  return !ADDRESS_TEXT.test(serialized) && !DOMAIN_TEXT.test(serialized) && !LEAK_TEXT.test(serialized)
    && !/(?:bytecode|\babi\b|rawSource|sourceCode|rawContent|targetString|downloadUrl)/i.test(serialized);
}

function compareFile(a, b) {
  return a.repositoryId.localeCompare(b.repositoryId) || a.path.localeCompare(b.path);
}
function validateFileRow(row) {
  return exactKeys(row, [
    "repositoryId", "path", "observedHeadSha", "blobCommitment", "declarationStatus",
    "chainId", "targetCommitment", "declarationCommitment"
  ]) && safeRepositoryId(row.repositoryId) && eligiblePath(row.repositoryId, row.path) && sha40(row.observedHeadSha)
    && sha64(row.blobCommitment) && ["RESOLVED", "UNRESOLVED"].includes(row.declarationStatus)
    && (row.chainId === null || numericChainId(row.chainId)) && sha64(row.targetCommitment, true)
    && sha64(row.declarationCommitment)
    && (row.declarationStatus === "RESOLVED"
      ? row.chainId !== null && row.targetCommitment !== null
      : row.targetCommitment === null);
}
function validateArtifact(value) {
  try {
    if (!exactKeys(value, ["schema", "generatedAt", "status", "sentinelCommitment", "scorerCommitment", "counts", "files", "safety"])
        || value.schema !== SCHEMA || !iso(value.generatedAt) || !["EMPTY", "INCOMPLETE"].includes(value.status)
        || !sha64(value.sentinelCommitment) || !sha64(value.scorerCommitment)
        || !exactKeys(value.counts, ["selectedFiles", "fetchedFiles", "resolvedFiles", "unresolvedFiles"])
        || Object.values(value.counts).some((count) => !Number.isSafeInteger(count) || count < 0 || count > MAX_SELECTED_FILES)
        || !Array.isArray(value.files) || value.files.length > MAX_SELECTED_FILES
        || value.files.some((row) => !validateFileRow(row))
        || JSON.stringify(value.files) !== JSON.stringify([...value.files].sort(compareFile))
        || new Set(value.files.map((row) => `${row.repositoryId}\0${row.path}`)).size !== value.files.length
        || value.counts.selectedFiles !== value.files.length || value.counts.fetchedFiles !== value.files.length
        || value.counts.resolvedFiles !== value.files.filter((row) => row.declarationStatus === "RESOLVED").length
        || value.counts.unresolvedFiles !== value.files.filter((row) => row.declarationStatus === "UNRESOLVED").length
        || value.counts.fetchedFiles !== value.counts.resolvedFiles + value.counts.unresolvedFiles
        || !exactKeys(value.safety, [
          "localOnly", "networkAccess", "rpcAccess", "forkUse", "pnlEvaluation", "signing", "transactions", "automaticExecution"
        ]) || typeof value.safety.localOnly !== "boolean" || typeof value.safety.networkAccess !== "boolean"
        || value.safety.localOnly !== !value.safety.networkAccess
        || value.safety.networkAccess !== (value.counts.selectedFiles > 0)
        || Object.entries(value.safety).some(([key, item]) => !["localOnly", "networkAccess"].includes(key) && item !== false)
        || !leakFree(value)) return false;
    return value.status === "EMPTY"
      ? value.files.length === 0 && Object.values(value.counts).every((count) => count === 0)
      : true;
  } catch (_) { return false; }
}

function normalizeNow(now) {
  const value = now === undefined ? Date.now() : (typeof now === "function" ? now() : now);
  if (!Number.isSafeInteger(value) || value < 0 || !Number.isFinite(new Date(value).getTime())) fail("INVALID_NOW");
  return value;
}
function strictReadJson(filename, fsImpl, errorCode) {
  let stat, raw;
  try {
    stat = fsImpl.lstatSync(filename);
    if (!stat.isFile() || stat.isSymbolicLink() || stat.size <= 0 || stat.size > MAX_INPUT_BYTES) fail(errorCode);
    raw = fsImpl.readFileSync(filename);
  } catch (error) {
    if (error instanceof ExtractorError) throw error;
    fail(error && error.code === "ENOENT" && errorCode === "SCORER_INVALID" ? "SCORER_MISSING" : errorCode);
  }
  if (!Buffer.isBuffer(raw) || raw.length <= 0 || raw.length > MAX_INPUT_BYTES) fail(errorCode);
  try { return JSON.parse(raw.toString("utf8")); } catch (_) { fail(errorCode); }
}
function loadInputs(options, now) {
  const fsImpl = options.fsImpl || fs;
  const scope = scopeModule.resolveScope(options.scope, options.scopeConfigPath);
  const sentinel = strictReadJson(options.sentinelPath || SENTINEL_PATH, fsImpl, "SENTINEL_INVALID");
  if (!sentinelModule.validateArtifact(sentinel)) fail("SENTINEL_INVALID");
  const assessment = scopeModule.assessSentinelScope(sentinel, scope);
  if (!assessment.ok) fail("SENTINEL_INVALID");
  const candidatePolls = sentinel.repositories.filter((repository) => repository.pollStatus === "candidate-change");
  if ((sentinel.status === "unchanged" && candidatePolls.length !== 0)
      || (sentinel.status === "candidate-change" && candidatePolls.length === 0)) fail("SENTINEL_INVALID");
  const sentinelMs = Date.parse(sentinel.generatedAt);
  if (sentinelMs > now + feedModule.MAX_FUTURE_SKEW_MS || now >= sentinelMs + feedModule.SENTINEL_MAX_AGE_MS) fail("SENTINEL_STALE");
  const effectiveStatus = assessment.effectiveStatus;

  const scorer = strictReadJson(options.scorerPath || SCORER_PATH, fsImpl, "SCORER_INVALID");
  const scorerMs = scorer && Date.parse(scorer.generatedAt);
  const sentinelCommitment = feedModule.sha256Canonical(sentinel);
  if (!scorerModule.validateArtifact(scorer) || scorer.sentinelCommitment !== sentinelCommitment
      || !Number.isFinite(scorerMs) || scorerMs < sentinelMs
      || scorerMs > now + feedModule.MAX_FUTURE_SKEW_MS || now >= scorerMs + feedModule.SENTINEL_MAX_AGE_MS
      || (effectiveStatus === "unchanged" && scorer.status !== "EMPTY")
      || (effectiveStatus === "candidate-change" && scorer.status !== "INCOMPLETE")) fail("SCORER_INVALID");
  const expectedScorer = scorerModule.scoreSentinel(sentinel, scorerMs, { effectiveStatus, excludedIds: scope.excludedIds });
  if (feedModule.canonicalJson(expectedScorer) !== feedModule.canonicalJson(scorer)) fail("SCORER_INVALID");
  return { sentinel, scorer, effectiveStatus, sentinelCommitment, scorerCommitment: feedModule.sha256Canonical(scorer), fsImpl };
}

function selectedFiles(scorer) {
  const files = [];
  for (const row of scorer.selected) {
    for (const selectedPath of row.selectedPaths) {
      if (eligiblePath(row.repositoryId, selectedPath)) files.push({
        repositoryId: row.repositoryId,
        path: selectedPath,
        observedHeadSha: row.observedHeadSha,
        classes: [...row.classes],
        scorerRowCommitment: feedModule.sha256Canonical(row)
      });
    }
  }
  files.sort(compareFile);
  return files.slice(0, MAX_SELECTED_FILES);
}

function encodedPath(value) { return value.split("/").map(encodeURIComponent).join("/"); }
function contentsUrl(repositoryId, filePath, observedHeadSha) {
  if (!safeRepositoryId(repositoryId) || !eligiblePath(repositoryId, filePath) || !sha40(observedHeadSha)) fail("REQUEST_INVALID");
  const repository = repositoryId.split("/").map(encodeURIComponent).join("/");
  return `https://api.github.com/repos/${repository}/contents/${encodedPath(filePath)}?ref=${observedHeadSha}`;
}
function validateContentsUrl(url, repositoryId, filePath, observedHeadSha) {
  try {
    const expected = contentsUrl(repositoryId, filePath, observedHeadSha);
    if (url !== expected) return false;
    const parsed = new URL(url);
    return parsed.protocol === "https:" && parsed.hostname === "api.github.com" && parsed.port === ""
      && parsed.username === "" && parsed.password === "" && parsed.hash === ""
      && parsed.searchParams.size === 1 && parsed.searchParams.get("ref") === observedHeadSha;
  } catch (_) { return false; }
}
function normalizedHeaders(headers) {
  const result = {};
  if (!headers || typeof headers !== "object") return result;
  for (const [key, value] of Object.entries(headers)) result[String(key).toLowerCase()] = Array.isArray(value) ? value.join(", ") : String(value);
  return result;
}
function responseBytes(body) {
  if (Buffer.isBuffer(body)) return body;
  if (typeof body === "string") return Buffer.from(body, "utf8");
  if (body && typeof body === "object") return Buffer.from(JSON.stringify(body), "utf8");
  fail("MALFORMED_RESPONSE");
}
function parseResponse(response, expectedPath) {
  if (!response || !Number.isInteger(response.status)) fail("MALFORMED_RESPONSE");
  if (response.status >= 300 && response.status < 400) fail("REDIRECT_REJECTED");
  if (response.status !== 200) fail("HTTP_FAILURE");
  const headers = normalizedHeaders(response.headers);
  if (!/^application\/(?:json|vnd\.github\+json)(?:\s*;|$)/i.test(headers["content-type"] || "")) fail("CONTENT_TYPE_INVALID");
  const bytes = responseBytes(response.body);
  if (bytes.length <= 0 || bytes.length > MAX_RESPONSE_BYTES) fail("RESPONSE_OVERSIZE");
  let raw;
  try { raw = JSON.parse(bytes.toString("utf8")); } catch (_) { fail("NON_JSON_RESPONSE"); }
  if (!ownObject(raw)) fail("CONTENT_INVALID");
  // The live Contents API also returns link/name/url fields. Only the bounded six-field
  // projection is validated and consumed, so extra fields are dropped and never persisted.
  const value = {};
  for (const key of CONTENT_KEYS) value[key] = raw[key];
  if (value.type !== "file" || value.path !== expectedPath
      || !sha40(value.sha) || !Number.isSafeInteger(value.size) || value.size < 0 || value.size > MAX_DECODED_BYTES
      || value.encoding !== "base64" || typeof value.content !== "string") fail("CONTENT_INVALID");
  return value;
}
function decodeBase64(content, expectedSize) {
  if (/\r(?!\n)/.test(content) || /[^A-Za-z0-9+/=\r\n]/.test(content)) fail("BASE64_INVALID");
  const normalized = content.replace(/\r?\n/g, "");
  if (normalized.length === 0) {
    if (expectedSize !== 0) fail("BASE64_INVALID");
    return Buffer.alloc(0);
  }
  if (normalized.length % 4 !== 0 || !/^(?:[A-Za-z0-9+/]{4})*(?:[A-Za-z0-9+/]{2}==|[A-Za-z0-9+/]{3}=)?$/.test(normalized)) fail("BASE64_INVALID");
  const decoded = Buffer.from(normalized, "base64");
  if (decoded.length !== expectedSize || decoded.length > MAX_DECODED_BYTES || decoded.toString("base64") !== normalized) fail("BASE64_INVALID");
  return decoded;
}
function gitBlobSha(bytes) {
  return crypto.createHash("sha1").update(`blob ${bytes.length}\0`).update(bytes).digest("hex");
}

function parseDeclarationsTransient(bytes, decodedContext = {}) {
  let text, parsed;
  try { text = new TextDecoder("utf-8", { fatal: true }).decode(bytes); } catch (_) { fail("MANIFEST_UTF8_INVALID"); }
  if (identityModule.exactChainIdForPath(decodedContext.repositoryId, decodedContext.path) !== null) {
    let source;
    try { source = aaveAddressBookModule.parseSource(text, decodedContext.path); }
    catch (_) { fail("MANIFEST_SOURCE_INVALID"); }
    const chains = [{ location: "$identity", key: "chainId", value: source.chainId }];
    const targets = [...source.targets];
    const minimalProjection = { chains, targets };
    return {
      summary: {
        declarationStatus: "RESOLVED",
        chainId: source.chainId,
        targetCommitment: feedModule.sha256Canonical(targets),
        declarationCommitment: feedModule.sha256Canonical(minimalProjection)
      },
      targets,
      parsedMapping: source.manifest
    };
  }
  try { parsed = JSON.parse(text); } catch (_) { fail("MANIFEST_NON_JSON"); }
  const chains = [], targets = [];
  const stack = [{ value: parsed, location: "$" }];
  let visited = 0;
  while (stack.length > 0) {
    const current = stack.pop();
    visited += 1;
    if (visited > MAX_DECLARATION_NODES) fail("MANIFEST_TOO_COMPLEX");
    if (Array.isArray(current.value)) {
      for (let index = current.value.length - 1; index >= 0; index -= 1) {
        stack.push({ value: current.value[index], location: `${current.location}[${index}]` });
      }
      continue;
    }
    if (!ownObject(current.value)) continue;
    const entries = Object.entries(current.value).sort(([a], [b]) => a.localeCompare(b));
    for (let index = entries.length - 1; index >= 0; index -= 1) {
      const [key, child] = entries[index];
      const location = `${current.location}/${key}`;
      if (key === "chainId" || key === "chain_id") chains.push({ location, key, value: child });
      const adapterTarget = decodedContext.repositoryId === "compound-finance/comet" && key === "comet";
      if ((TARGET_KEYS.has(key) || adapterTarget) && typeof child === "string" && EVM_ADDRESS.test(child)) {
        targets.push({ location, key, address: child.toLowerCase() });
      }
      if (child && typeof child === "object") stack.push({ value: child, location });
    }
  }
  if (chains.length === 0 && ADAPTER_REPOSITORIES.has(decodedContext.repositoryId)
      && typeof decodedContext.path === "string") {
    const pathChainIds = [...new Set(decodedContext.path.split("/").filter(numericChainId))];
    if (pathChainIds.length === 1) chains.push({ location: "$manifestPath", key: "chainId", value: pathChainIds[0] });
  }
  chains.sort((a, b) => a.location.localeCompare(b.location) || a.key.localeCompare(b.key));
  targets.sort((a, b) => a.location.localeCompare(b.location) || a.key.localeCompare(b.key) || a.address.localeCompare(b.address));
  const chainId = chains.length === 1 && numericChainId(chains[0].value) ? chains[0].value : null;
  const minimalProjection = {
    chains: chains.map((row) => ({ location: row.location, key: row.key, value: typeof row.value === "string" ? row.value : null })),
    targets
  };
  const declarationCommitment = feedModule.sha256Canonical(minimalProjection);
  const resolved = chainId !== null && targets.length > 0;
  return {
    summary: {
    declarationStatus: resolved ? "RESOLVED" : "UNRESOLVED",
    chainId,
    targetCommitment: resolved ? feedModule.sha256Canonical(targets) : null,
    declarationCommitment
    },
    targets,
    parsedMapping: parsed
  };
}
function parseDeclarations(bytes) { return parseDeclarationsTransient(bytes).summary; }

function createDefaultTransport() {
  return function transport(url, options) {
    return new Promise((resolve, reject) => {
      let settled = false;
      const finish = (callback, value) => { if (!settled) { settled = true; callback(value); } };
      let request;
      try {
        const parsed = new URL(url);
        if (parsed.protocol !== "https:" || parsed.hostname !== "api.github.com" || parsed.port || parsed.username || parsed.password || parsed.hash) {
          fail("REQUEST_INVALID");
        }
        request = https.request(parsed, { method: "GET", headers: options.headers }, (response) => {
          const chunks = [];
          let total = 0;
          const declared = Number(response.headers["content-length"] || 0);
          if (declared > options.maxBytes) { response.destroy(); finish(reject, new ExtractorError("RESPONSE_OVERSIZE")); return; }
          response.on("data", (chunk) => {
            total += chunk.length;
            if (total > options.maxBytes) { response.destroy(); finish(reject, new ExtractorError("RESPONSE_OVERSIZE")); }
            else chunks.push(chunk);
          });
          response.on("error", (error) => finish(reject, error));
          response.on("end", () => finish(resolve, { status: response.statusCode || 0, headers: response.headers, body: Buffer.concat(chunks) }));
        });
      } catch (error) { reject(error); return; }
      request.setTimeout(options.timeoutMs, () => request.destroy(new ExtractorError("TRANSPORT_TIMEOUT")));
      request.on("error", (error) => finish(reject, error));
      request.end();
    });
  };
}

async function fetchFileTransient(selected, transport) {
  const url = contentsUrl(selected.repositoryId, selected.path, selected.observedHeadSha);
  if (!validateContentsUrl(url, selected.repositoryId, selected.path, selected.observedHeadSha)) fail("REQUEST_INVALID");
  let response;
  try {
    response = await transport(url, {
      method: "GET",
      headers: { "User-Agent": USER_AGENT, Accept: "application/vnd.github+json", "X-GitHub-Api-Version": "2022-11-28" },
      timeoutMs: TIMEOUT_MS,
      maxBytes: MAX_RESPONSE_BYTES,
      maxRedirects: 0,
      retries: 0
    });
  } catch (error) {
    if (error instanceof ExtractorError) throw error;
    fail("TRANSPORT_FAILURE");
  }
  const content = parseResponse(response, selected.path);
  const decoded = decodeBase64(content.content, content.size);
  if (gitBlobSha(decoded) !== content.sha) fail("BLOB_SHA_MISMATCH");
  const declarations = parseDeclarationsTransient(decoded, {
    repositoryId: selected.repositoryId,
    path: selected.path
  });
  const file = {
      repositoryId: selected.repositoryId,
      path: selected.path,
      observedHeadSha: selected.observedHeadSha,
      blobCommitment: crypto.createHash("sha256").update(decoded).digest("hex"),
      ...declarations.summary
  };
  return {
    file,
    targets: declarations.targets.map((target, ordinal) => ({
      targetKey: target.key,
      record: {
        upstreamRecordCommitment: feedModule.sha256Canonical({
          declarationCommitment: declarations.summary.declarationCommitment,
          ordinal,
          location: target.location,
          key: target.key
        }),
        chainId: declarations.summary.chainId,
        address: target.address,
        topology: "UNRESOLVED",
        upstreamAuthorityCommitment: null,
        expectedBuildCommitment: null,
        expectedRuntimeCommitment: null
      },
      context: {
        repositoryId: selected.repositoryId,
        pinnedCommitSha: selected.observedHeadSha,
        manifestPath: selected.path,
        blobCommitment: file.blobCommitment,
        declarationCommitment: declarations.summary.declarationCommitment,
        parsedMapping: declarations.parsedMapping,
        topology: /proxy/i.test(target.key) ? "EIP1967_PROXY" : "DIRECT",
        scorerCommitment: selected.scorerRowCommitment,
        classes: [...selected.classes]
      }
    }))
  };
}
async function fetchFile(selected, transport) { return (await fetchFileTransient(selected, transport)).file; }

function mappingInputsForPipeline(transientRecords, pipelineContexts, upstreamExtractorCommitment,
    adapterDispatch = adapterModule.dispatch) {
  if (!Array.isArray(transientRecords) || !Array.isArray(pipelineContexts)
      || transientRecords.length !== pipelineContexts.length || !sha64(upstreamExtractorCommitment)
      || typeof adapterDispatch !== "function") fail("MAPPING_INPUT_INVALID");
  const mappingInputs = [];
  for (let index = 0; index < transientRecords.length; index += 1) {
    const record = transientRecords[index];
    const context = pipelineContexts[index];
    if (!ownObject(record) || !ownObject(context)) fail("MAPPING_INPUT_INVALID");
    if (!ADAPTER_REPOSITORIES.has(context.repositoryId)) {
      mappingInputs.push({
        upstreamRecordCommitment: record.upstreamRecordCommitment,
        manifestBlobCommitment: context.blobCommitment,
        declarationCommitment: context.declarationCommitment,
        pinnedCommitCommitment: feedModule.sha256Canonical({
          repositoryId: context.repositoryId,
          pinnedCommitSha: context.pinnedCommitSha
        }),
        parsedMapping: context.parsedMapping
      });
      continue;
    }
    let adapted;
    try {
      adapted = adapterDispatch({
        repositoryId: context.repositoryId,
        pinnedCommit: context.pinnedCommitSha,
        manifestPath: context.manifestPath,
        manifestBlobCommitment: context.blobCommitment,
        declarationCommitment: context.declarationCommitment,
        upstreamExtractorCommitment,
        upstreamRecordCommitment: record.upstreamRecordCommitment,
        manifest: context.parsedMapping
      });
    } catch (_) { continue; }
    if (!adapterModule.validateResult(adapted) || adapted.status !== "EXACT" || adapted.transient === null) continue;
    if (adapted.transient.upstreamRecordCommitment !== record.upstreamRecordCommitment
        || adapted.transient.manifestBlobCommitment !== context.blobCommitment
        || adapted.transient.declarationCommitment !== context.declarationCommitment) continue;
    mappingInputs.push(adapted.transient);
  }
  return mappingInputs;
}

function ensureDirectory(directory, fsImpl) {
  fsImpl.mkdirSync(directory, { recursive: true });
  const stat = fsImpl.lstatSync(directory);
  if (!stat.isDirectory() || stat.isSymbolicLink()) fail("OUTPUT_DIRECTORY_INVALID");
}
function publishAtomic(artifact, options = {}) {
  if (!validateArtifact(artifact)) fail("ARTIFACT_INVALID");
  const fsImpl = options.fsImpl || fs;
  const outputPath = path.resolve(options.outputPath || OUTPUT);
  const directory = path.dirname(outputPath);
  ensureDirectory(directory, fsImpl);
  const bytes = Buffer.from(`${JSON.stringify(artifact, null, 2)}\n`, "utf8");
  if (bytes.length > MAX_OUTPUT_BYTES) fail("OUTPUT_TOO_LARGE");
  const temporary = path.join(directory, `.${path.basename(outputPath)}.${process.pid}.${crypto.randomBytes(8).toString("hex")}.tmp`);
  let descriptor;
  try {
    descriptor = fsImpl.openSync(temporary, "wx", 0o600);
    fsImpl.writeFileSync(descriptor, bytes);
    fsImpl.fsyncSync(descriptor);
    fsImpl.closeSync(descriptor);
    descriptor = undefined;
    fsImpl.renameSync(temporary, outputPath);
    const readback = fsImpl.readFileSync(outputPath);
    if (!Buffer.isBuffer(readback) || !readback.equals(bytes)) fail("READBACK_INVALID");
    let parsed;
    try { parsed = JSON.parse(readback.toString("utf8")); } catch (_) { fail("READBACK_INVALID"); }
    if (!validateArtifact(parsed)) fail("READBACK_INVALID");
    return outputPath;
  } finally {
    if (descriptor !== undefined) try { fsImpl.closeSync(descriptor); } catch (_) {}
    try { if (fsImpl.existsSync(temporary)) fsImpl.unlinkSync(temporary); } catch (_) {}
  }
}

async function runAndPublish(options = {}) {
  const now = normalizeNow(options.now);
  const inputs = loadInputs(options, now);
  const selected = selectedFiles(inputs.scorer);
  const files = [], transientRecords = [], pipelineContexts = [];
  const aaveDeclarationCommitments = new Map();
  const emittedAaveTargets = new Set();
  if (inputs.effectiveStatus === "candidate-change" && selected.length > 0) {
    const transport = options.transport || createDefaultTransport();
    for (const row of selected) {
      const extracted = await fetchFileTransient(row, transport);
      files.push(extracted.file);
      const exactChainId = identityModule.exactChainIdForPath(row.repositoryId, row.path);
      if (exactChainId !== null) {
        const priorCommitment = aaveDeclarationCommitments.get(row.repositoryId);
        if (priorCommitment !== undefined && priorCommitment !== extracted.file.declarationCommitment) {
          fail("MIRRORED_DECLARATION_MISMATCH");
        }
        aaveDeclarationCommitments.set(row.repositoryId, extracted.file.declarationCommitment);
      }
      for (const target of extracted.targets) {
        if (exactChainId !== null) {
          const identity = `${row.repositoryId}\0${exactChainId}\0${target.targetKey}\0${target.record.address}`;
          if (emittedAaveTargets.has(identity)) continue;
          emittedAaveTargets.add(identity);
        }
        transientRecords.push(target.record);
        pipelineContexts.push(target.context);
      }
    }
  }
  files.sort(compareFile);
  const artifact = {
    schema: SCHEMA,
    generatedAt: new Date(now).toISOString(),
    status: inputs.effectiveStatus === "unchanged" ? "EMPTY" : "INCOMPLETE",
    sentinelCommitment: inputs.sentinelCommitment,
    scorerCommitment: inputs.scorerCommitment,
    counts: {
      selectedFiles: selected.length,
      fetchedFiles: files.length,
      resolvedFiles: files.filter((row) => row.declarationStatus === "RESOLVED").length,
      unresolvedFiles: files.filter((row) => row.declarationStatus === "UNRESOLVED").length
    },
    files,
    safety: safetyFields(selected.length > 0)
  };
  if (!validateArtifact(artifact)) fail("ARTIFACT_INVALID");
  const upstreamExtractorCommitment = feedModule.sha256Canonical(artifact);
  const usesRepositoryAdapter = pipelineContexts.some((context) => ADAPTER_REPOSITORIES.has(context.repositoryId));
  const adapterDispatch = usesRepositoryAdapter
    ? (options.adapterDispatch || adapterModule.dispatch)
    : adapterModule.dispatch;
  const mappingInputs = mappingInputsForPipeline(
    transientRecords,
    pipelineContexts,
    upstreamExtractorCommitment,
    adapterDispatch
  );
  const mappingArtifact = mappingModule.runAndPublish({
    records: mappingInputs,
    upstreamExtractorCommitment,
    now,
    fsImpl: inputs.fsImpl,
    outputPath: options.mappingOutputPath || mappingModule.OUTPUT
  });
  const resolveMapping = mappingModule.exactResolver(mappingArtifact);
  const metadataInputs = [];
  for (let index = 0; index < transientRecords.length; index += 1) {
    const record = transientRecords[index];
    const context = pipelineContexts[index];
    const mapped = resolveMapping(record);
    if (mapped) metadataInputs.push({
      repositoryId: context.repositoryId,
      metadataPath: mapped.metadataPath,
      pinnedCommitSha: context.pinnedCommitSha,
      upstreamExtractorCommitment,
      upstreamRecordCommitment: record.upstreamRecordCommitment,
      mappingCommitment: mapped.mappingCommitment,
      metadataPathCommitment: mapped.metadataPathCommitment,
      manifestBlobCommitment: context.blobCommitment,
      declarationCommitment: context.declarationCommitment,
      sourceName: mapped.sourceName,
      contractName: mapped.contractName
    });
  }
  const metadataArtifact = await metadataModule.runAndPublish({
    records: metadataInputs,
    upstreamExtractorCommitment,
    transport: metadataInputs.length > 0 ? (options.transport || createDefaultTransport()) : undefined,
    now,
    fsImpl: inputs.fsImpl,
    outputPath: options.metadataOutputPath || metadataModule.OUTPUT
  });
  const resolveMetadata = metadataModule.exactResolver(metadataArtifact);
  const authorityInputs = [];
  for (let index = 0; index < transientRecords.length; index += 1) {
    const record = transientRecords[index];
    const context = pipelineContexts[index];
    const exact = resolveMetadata(record);
    if (exact) {
      authorityInputs.push({
        upstreamExtractorCommitment,
        upstreamRecordCommitment: record.upstreamRecordCommitment,
        sourceCommitment: exact.standardInputCommitment,
        blobCommitment: exact.metadataBlobCommitment,
        declarationCommitment: context.declarationCommitment,
        compilerSettingsCommitment: exact.compilerSettingsCommitment,
        standardInputCommitment: exact.standardInputCommitment,
        buildRuntimeCommitment: exact.deployedRuntimeCommitment,
        upstreamMetadataCommitment: exact.buildMetadataCommitment,
        topology: context.topology
      });
    } else authorityInputs.push({ upstreamRecordCommitment: record.upstreamRecordCommitment });
  }
  const authorityArtifact = authorityModule.runAndPublish({
    records: authorityInputs,
    upstreamExtractorCommitment,
    now,
    fsImpl: inputs.fsImpl,
    outputPath: options.authorityOutputPath || authorityModule.OUTPUT
  });
  const resolveExpected = authorityModule.expectedResolver(authorityArtifact);
  for (const record of transientRecords) {
    const expected = resolveExpected(record);
    if (!expected) continue;
    record.topology = expected.topology;
    record.upstreamAuthorityCommitment = expected.authorityCommitment;
    record.expectedBuildCommitment = expected.expectedBuildCommitment;
    record.expectedRuntimeCommitment = expected.expectedRuntimeCommitment;
  }
  const observations = transientRecords.map(() => []);
  let runtimeInvoked = false;
  if (typeof options.runtimeQualifier === "function") {
    for (let index = 0; index < transientRecords.length; index += 1) {
      const record = transientRecords[index];
      const complete = typeof record.chainId === "string" && /^[1-9][0-9]{0,19}$/.test(record.chainId)
        && ["DIRECT", "EIP1967_PROXY"].includes(record.topology) && /^[0-9a-f]{64}$/.test(record.expectedBuildCommitment || "")
        && /^[0-9a-f]{64}$/.test(record.expectedRuntimeCommitment || "")
        && /^[0-9a-f]{64}$/.test(record.upstreamAuthorityCommitment || "");
      if (!complete) continue;
      runtimeInvoked = true;
      try { observations[index] = options.runtimeQualifier(record, index); } catch (_) { observations[index] = null; }
    }
  }
  const binderArtifact = binderModule.runAndPublish({
    records: transientRecords,
    observations,
    upstreamBatchCommitment: upstreamExtractorCommitment,
    now,
    networkAccess: runtimeInvoked,
    rpcAccess: runtimeInvoked,
    fsImpl: inputs.fsImpl,
    outputPath: options.binderOutputPath || binderModule.OUTPUT
  });
  const authorityRows = authorityArtifact.rows.map((row) => ({
    recordCommitment: row.upstreamRecordCommitment,
    authorityCommitment: row.authorityCommitment,
    status: row.status
  }));
  const bindingByAuthority = new Map(binderArtifact.bindings
    .filter((binding) => binding.authorityCommitment !== null)
    .map((binding) => [binding.authorityCommitment, binding]));
  const binderRows = authorityArtifact.rows.filter((row) => row.authorityCommitment !== null)
    .map((row) => {
      const binding = bindingByAuthority.get(row.authorityCommitment);
      return binding ? {
        recordCommitment: row.upstreamRecordCommitment,
        authorityCommitment: row.authorityCommitment,
        binderCommitment: binding.bindingCommitment,
        status: binding.status
      } : null;
    }).filter(Boolean);
  const scorerRows = transientRecords.map((record, index) => ({
    recordCommitment: record.upstreamRecordCommitment,
    scorerCommitment: pipelineContexts[index].scorerCommitment,
    classes: [...pipelineContexts[index].classes]
  }));
  plannerModule.runAndPublish({
    upstreamExtractorCommitment,
    authorityBatchCommitment: authorityArtifact.authorityBatchCommitment,
    binderBatchCommitment: binderArtifact.bindingBatchCommitment,
    scorerBatchCommitment: inputs.scorerCommitment,
    authorityRows,
    binderRows,
    scorerRows,
    now,
    fsImpl: inputs.fsImpl,
    outputPath: options.invariantOutputPath || plannerModule.OUTPUT
  });
  publishAtomic(artifact, { fsImpl: inputs.fsImpl, outputPath: options.outputPath || OUTPUT });
  return artifact;
}

async function main(argv = process.argv.slice(2)) {
  if (!Array.isArray(argv) || argv.length !== 0) {
    process.stderr.write("deployed-delta-manifest-extractor: unsupported arguments\n");
    process.exitCode = 2;
    return;
  }
  try {
    const artifact = await runAndPublish();
    process.stdout.write(`deployed-delta-manifest-extractor: ${artifact.status}\n`);
  } catch (error) {
    process.stderr.write(`deployed-delta-manifest-extractor: ${error instanceof ExtractorError ? error.code : "FAILED"}\n`);
    process.exitCode = 1;
  }
}

