"use strict";

const fs = require("fs");
const path = require("path");
const crypto = require("crypto");
const NAME = "critical-across-sponsored-cctp-receive-false-premise-step1";
const CLASSIFICATION = "CLOSED/FALSE-PERMISSIONLESS-PREMISE/PRIVILEGED-EMERGENCY/CCTP-AND-SIGNATURE-BOUND-NORMAL/PREEXISTING-BALANCE-PROTECTED";
const ROOT = path.resolve(__dirname, "..");
const RAW = `reports/raw/fast/${NAME}.json`;
const TESTS = `reports/raw/fast/${NAME}-tests.json`;
const MANIFEST = `reports/raw/fast/${NAME}-manifest.json`;
const INBOX = `coordination/inbox/critical/2026-07-26-${NAME}.json`;
const read = (relative) => fs.readFileSync(path.join(ROOT, relative));
const json = (relative) => JSON.parse(read(relative));
const sha = (value) => crypto.createHash("sha256").update(value).digest("hex");
const checks = [];
const check = (condition, label) => { if (!condition) throw new Error(label); checks.push(label); };

const raw = json(RAW);
const tests = json(TESTS);
const manifest = json(MANIFEST);
const inbox = json(INBOX);
check(raw.classification === CLASSIFICATION && manifest.classification === CLASSIFICATION, "classification");
check(raw.pipeline.branch === 0 && raw.pipeline.total === 5, "branch-0-of-5");
check(raw.gates.routePositive === 0 && raw.gates.executableNow === 0 && raw.gates.signedActionJustified === false && raw.gates.fork === false, "gates");
check(raw.conclusions.emergency.permissionless === false && raw.conclusions.emergency.requiredRole === "PERMISSIONED_BOT_ROLE", "privileged-emergency");
check(raw.conclusions.emergency.preexistingBalanceForwarded === false && raw.conclusions.emergency.transmitterFalseBehavior === "return without forwarding", "emergency-delta");
check(raw.conclusions.normal.submissionPermissionless === true && raw.conclusions.normal.executionBoundBy.length === 5, "permissionless-submission-bound-execution");
check(raw.conclusions.normal.underMintAccepted === false && raw.conclusions.normal.overMintAccepted === false && raw.conclusions.normal.replayAccepted === false, "normal-conservation-replay");
check(raw.conclusions.operationalStranding.includes("newly minted funds join custody") && raw.conclusions.profit === 0, "stranding-not-redirection");
check(raw.conclusions.callbacks.includes("no duplicate forwarding"), "callbacks");
check(tests.testsPassed === 13 && tests.testsFailed === 0 && tests.fuzzCases >= 256 && tests.effectiveCases === 268, "tests-fuzz");
check(tests.deterministicReplay === true && tests.replayCount === 2 && /^[0-9a-f]{64}$/.test(tests.normalizedPassOutputSha256), "deterministic-replay");
check(raw.productionBinding.commit === manifest.productionCommit && raw.productionBinding.sources.length === 8 && raw.productionBinding.productionSourcesModified === false, "production-binding");
check(manifest.localHarness.harnessRuntimeSha256 === tests.isolatedCompile.harnessRuntimeSha256 && tests.isolatedCompile.limitations.includes("ERC-1271"), "harness-byte-binding-limitations");
check(raw.activityScope.rpcCalls === 0 && raw.activityScope.httpRequests === 0 && raw.activityScope.forkCreated === false && raw.activityScope.signing === false && raw.activityScope.broadcasts === 0, "offline-safety");
check(inbox.routePositive === 0 && inbox.executableNow === 0 && inbox.signedActionJustified === false && inbox.fork === false, "inbox-gates");
const records = manifest.records.map((item) => {
  const value = read(item.path);
  check(value.length === item.bytes && sha(value) === item.sha256, `record:${item.path}`);
  return { path: item.path, bytes: value.length, sha256: sha(value) };
});
const aggregate = sha(Buffer.from(records.map((item) => `${item.path}\0${item.bytes}\0${item.sha256}`).join("\n")));
check(aggregate === manifest.aggregateSha256, "aggregate");
process.stdout.write(`${JSON.stringify({ ok: true, checksPassed: checks.length, checksTotal: checks.length, runId: raw.runId, classification: CLASSIFICATION, tests: "13/13", fuzzCases: tests.fuzzCases, effectiveCases: tests.effectiveCases, replayCount: tests.replayCount, normalizedPassOutputSha256: tests.normalizedPassOutputSha256, harnessRuntimeSha256: tests.isolatedCompile.harnessRuntimeSha256, manifestSha256: sha(read(MANIFEST)), aggregateSha256: aggregate })}\n`);
