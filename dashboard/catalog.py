"""The fixed dashboard catalog and source freshness metadata."""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Monitor:
    id: str
    name: str
    disposition: str
    note: str
    protocol: str
    mode: str
    source: str = "NO_SOURCE"
    cadence: int | None = None
    aging_after: int | None = None
    stale_after: int | None = None

    def freshness_limits(self) -> tuple[int, int]:
        """Return explicit limits or continuous defaults from cadence."""

        if self.aging_after is not None and self.stale_after is not None:
            return self.aging_after, self.stale_after
        if self.mode == "CONTINUOUS" and self.cadence is not None:
            return self.cadence * 2, self.cadence * 6
        return 86_400, 604_800


